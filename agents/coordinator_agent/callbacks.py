import json
import logging
import re

import httpx
from google.adk.agents.callback_context import CallbackContext

from config.agents_config import INCIDENT_API_BASE_URL
from services.langsmith_service import record_agent_report

logger = logging.getLogger(__name__)


def save_incident_context(callback_context: CallbackContext):
    for event in callback_context.session.events:
        if event.author == "user" and event.content:
            for part in event.content.parts or []:
                match = re.search(r"Incident ID:\s*([A-Za-z0-9-]+)", part.text or "")

                if match:
                    callback_context.state["incident_id"] = match.group(1)
                    break


def save_monitoring_output(callback_context: CallbackContext):
    for event in reversed(callback_context.session.events):
        if (
            event.author == callback_context.agent_name
            and event.content
            and event.content.parts
        ):
            monitoring_output = "".join(part.text or "" for part in event.content.parts)

            callback_context.state["monitoring_output"] = monitoring_output
            logger.info("Monitoring output saved to state.")

            record_agent_report(
                callback_context.state.get("incident_id", "unknown"),
                "Monitoring Agent",
                monitoring_output,
            )
            break


