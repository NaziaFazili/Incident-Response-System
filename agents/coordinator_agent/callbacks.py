def save_remediation_output(callback_context: CallbackContext):
    try:
        for event in reversed(callback_context.session.events):
            if (
                event.author == callback_context.agent_name
                and event.content
                and event.content.parts
            ):
                remediation_output = "".join(
                    part.text or "" for part in event.content.parts
                )
                callback_context.state["remediation_output"] = remediation_output
                # Get the HTN plan generated by the Remediation Agent
                plan = json.loads(callback_context.state["remediation_output"])

                # Get the recommended remediation action
                recommended_action = plan["recommended_action"]

                # Get the incident ID from the plan
                incident_id = plan["plan_id"].removeprefix("plan-")
                record_agent_report(
                    incident_id,
                    "Remediation Agent",
                    remediation_output,
                )
                logger.info(
                    "[HITL] Starting approval for incident %s, action: %s",
                    incident_id,
                    recommended_action,
                )

                # Automatically start HITL approval
                api_base_url = INCIDENT_API_BASE_URL.rstrip("/")
                response = httpx.post(
                    f"{api_base_url}/api/incidents/{incident_id}/request-approval",
                    json={"recommended_action": recommended_action},
                    timeout=15.0,
                )
                logger.info(
                    "[HITL] FastAPI response: %s - %s",
                    response.status_code,
                    response.text,
                )

                response.raise_for_status()
                logger.info(
                    "[HITL] Approval workflow started for incident %s",
                    incident_id,
                )

                break
    except (json.JSONDecodeError, KeyError, ValueError) as ex:
        logger.exception(
            "[REMEDIATION] Invalid remediation plan: %s",
            ex,
        )
        raise
    except httpx.HTTPStatusError as ex:
        logger.error(
            "[HITL] FastAPI returned error %s: %s",
            ex.response.status_code,
            ex.response.text,
        )
        raise

    except httpx.RequestError:
        logger.exception(
            "[HITL] Could not connect to FastAPI at %s",
            INCIDENT_API_BASE_URL,
        )
        raise
    except Exception:
        logger.exception("[HITL] Failed to start remediation approval workflow.")
        raise
